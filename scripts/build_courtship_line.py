def callsign_daily_patches():
    patches = []
    for cid, form in CALLSIGN_FORMS.items():
        dating = {}
        for day, text in CALLSIGN_DATING.items():
            line = text.replace('{cs}', form)
            dating[f'{day}8'] = dating[f'{day}10'] = line
        patches.append({**patch(f'Courtship §5.3 — позывной в репликах дня (Dating, {cid})', 'Characters/Dialogue/Harvey', dating),
                        'Priority': 'Late + 3',
                        'When': {'Relationship:Harvey': 'Dating', **when_flag(f'HarveyRomance_Callsign_{cid}'), **CALLSIGN_DAY}})
        patches.append({**patch(f'Courtship §5.3 — позывной в репликах брака ({cid})', 'Characters/Dialogue/MarriageDialogueHarvey',
                                {k: v.replace('{cs}', form) for k, v in CALLSIGN_MARRIED.items()}),
                        'Priority': 'Late + 3',
                        'When': {'Relationship:Harvey': 'Married', **when_flag(f'HarveyRomance_Callsign_{cid}'), **CALLSIGN_DAY}})
    return patches


