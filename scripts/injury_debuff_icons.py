    ink = palette['o']

    def tile(source):
        rows = [row.strip() for row in source.strip().splitlines()]
        assert len(rows) <= 16 and all(len(row) <= 16 for row in rows), rows
        rows = [row.ljust(16, '.') for row in rows] + ['.'*16]*(16-len(rows))
        image = Image.new('RGBA', (16, 16))
        image.putdata([palette[key] for row in rows for key in row])
        return contour(image)

    def contour(image):
        source = image.copy()
        for y in range(16):
            for x in range(16):
                if source.getpixel((x, y))[3] and any(
                    not (0 <= xx < 16 and 0 <= yy < 16) or not source.getpixel((xx, yy))[3]
                    for xx, yy in ((x-1, y), (x+1, y), (x, y-1), (x, y+1))
                ):
                    image.putpixel((x, y), ink)
        return image

    def paint(base, marks):
        image = base.copy()
        for x, y, color in marks:
            if image.getpixel((x, y))[3] and image.getpixel((x, y)) != ink:
                image.putpixel((x, y), palette[color])
        return image

    def recolor(base, replacements):
        image = base.copy()
        table = {palette[a]: palette[b] for a, b in replacements.items()}
        image.putdata([table.get(pixel, pixel) for pixel in image.get_flattened_data()])
        return image

