def preview(art, atlas, index):
    """Review the exact runtime cells at native size and enlarged, never samples art."""
    from PIL import ImageDraw, ImageFont
    examples = [
        ('Перелом кости', 'buffFracturedBone'), ('Лодыжка', 'buffSprainedAnkle'),
        ('Ушиб рёбер', 'buffBruisedRibs'), ('Растяжение спины', 'buffBackStrain'),
        ('Глубокие порезы', 'buffDeepCuts'), ('Ожог', 'buffBurnWounds'),
        ('Надрыв мышцы', 'buffTornMuscles'), ('Сотрясение', 'buffConcussion'),
        ('Осколочные раны', 'buffShrapnelWounds'), ('Инфекция', 'buffInfectedWound'),
        ('Отравление', 'buffAlcoholPoisoning'), ('Послеоперационные швы', 'buffSurgicalWound'),
        ('Мокрая повязка', 'HarveyMod_WetBandage'), ('Аллергическая сыпь', 'HarveyMod_AllergicRash'),
        ('Затруднённое дыхание', 'HarveyMod_BreathingDifficulty'), ('Заражение крови', 'HarveyMod_Sepsis'),
    ]
    art.mkdir(parents=True, exist_ok=True)
    exports = art / 'exports'
    exports.mkdir(exist_ok=True)
    path = 'C:/Windows/Fonts/arial.ttf'
    title = ImageFont.truetype(path, 25)
    font = ImageFont.truetype(path, 17)
    small = ImageFont.truetype(path, 13)
    canvas = Image.new('RGB', (1040, 830), '#e9dcba')
    draw = ImageDraw.Draw(canvas)
    draw.text((24, 16), 'ДЕБАФФЫ ТРАВМ · ОТДЕЛЬНЫЙ СИМВОЛ ДЛЯ КАЖДОЙ ТРАВМЫ', font=title, fill='#301e25')
    draw.text((24, 51), 'Игровые рисунки 16×16 · увеличение ×6 и ×3 без сглаживания', font=font, fill='#655363')
    before_path = art / 'before/harveyBuffIcons.png'
    before = Image.open(before_path).convert('RGBA') if before_path.exists() else None
    comparison = Image.new('RGB', (1040, 900), '#e9dcba')
    cd = ImageDraw.Draw(comparison)
    cd.text((24, 16), 'ДЕБАФФЫ ТРАВМ · СРАВНЕНИЕ С ПРЕДЫДУЩЕЙ ВЕРСИЕЙ', font=title, fill='#301e25')
    for pos, (label, key) in enumerate(examples):
        i = index[key]
        box = (i%16*16, i//16*16, i%16*16+16, i//16*16+16)
        icon = atlas.crop(box)
        icon.save(exports / f'{key}.png')
        x, y = 24+pos%4*256, 97+pos//4*178
        draw.text((x, y), label, font=font, fill='#301e25')
        draw.rectangle((x, y+28, x+95, y+123), fill='#ba9976')
        big = icon.resize((96, 96), Image.Resampling.NEAREST)
        canvas.paste(big, (x, y+28), big)
        canvas.paste(icon, (x+117, y+31), icon)
        draw.text((x+140, y+31), '16 px', font=small, fill='#655363')
        draw.rectangle((x+114, y+75, x+165, y+126), fill='#343645')
        enlarged = icon.resize((48, 48), Image.Resampling.NEAREST)
        canvas.paste(enlarged, (x+116, y+77), enlarged)
        cx, cy = 24+pos%4*256, 78+pos//4*200
        cd.text((cx, cy), label, font=font, fill='#301e25')
        for offset, source, caption in ((0, before, 'Было'), (125, atlas, 'Стало')):
            if source is None:
                continue
            t = source.crop(box)
            scaled = t.resize((80, 80), Image.Resampling.NEAREST)
            cd.rectangle((cx+offset, cy+31, cx+offset+79, cy+110), fill='#ba9976')
            comparison.paste(scaled, (cx+offset, cy+31), scaled)
            cd.text((cx+offset, cy+116), caption, font=small, fill='#655363')
            comparison.paste(t, (cx+offset, cy+143), t)
        cd.text((cx+91, cy+59), '→', font=font, fill='#655363')
    canvas.save(art / 'preview.png')
    comparison.save(art / 'comparison.png')
